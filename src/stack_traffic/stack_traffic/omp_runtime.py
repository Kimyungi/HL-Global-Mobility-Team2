# -*- coding: utf-8 -*-
"""OpenMP 워커가 놀 때 도는(스핀) 것을 막는다.

**import 만으로 동작한다.** node.py 가 torch/ultralytics 보다 **먼저** 이 모듈을
import 해야 한다 — OpenMP 런타임은 초기화 시점에 환경변수를 한 번만 읽는다.

왜 필요한가
-----------
Intel OpenMP 는 작업을 끝낸 워커를 ``KMP_BLOCKTIME``(기본 200ms) 동안 **스핀**시킨
뒤에야 재운다. 다음 작업이 곧 온다는 가정에서 깨우는 지연을 아끼는 최적화다.
그런데 이 노드는 10fps(주기 100ms)라 블록타임이 주기보다 길어 **워커가 영영 안
잔다**.

2026-08-29 실측 (Xanadu-book5, 8코어):

* 워커 7개가 각각 ~67% 로 **균일하게** 돌아 노드 혼자 **487% CPU**(4.9코어)
* 실제 계산은 그 1/3 뿐이다 — YOLOv8n 640 추론의 CPU 시간은 프레임당 153ms
  (= 10fps 에서 153%) 로 따로 측정됐다. 나머지는 전부 스핀이다.

그 스핀이 노드 자신보다 **시스템 전체**를 더 해쳤다. 라이다 4대 + 카메라 2대를
동시에 돌리며 잰 MGM 10ms 루프 지터(CLAUDE.md §7 판정 근거):

======================  ==================  ==============
상태                    late max            load average
======================  ==================  ==============
신호등 끔               2.26 ms             --
신호등 켬 (스핀 그대로) 3.34 ms             12.0
신호등 켬 (이 설정)     **0.68 ms**         **1.8**
======================  ==================  ==============

즉 이 설정이면 신호등을 **켜고도** 끄고 돌 때보다 지터가 좋아진다.

대가
----
프레임당 처리시간 중앙 37.7 -> 48.8ms (스레드를 재우고 깨우는 비용)지만 10fps
예산 100ms 안이고, 파이프라인 fps 는 9.6(min 8.7) -> **10.0 안정**으로 오히려
좋아졌다. **정확도는 전혀 건드리지 않는다** — 계산 내용이 아니라 대기 방식이다.

코어 고정(``taskset -c 4,5,6``)도 487 -> 140% 로 비슷한 효과를 내지만, 그건 증상을
가두는 것이고 이건 원인을 없앤다. 코어 배분을 손으로 관리하지 않아도 된다.

되돌리기
--------
``setdefault`` 라 밖에서 준 값을 덮지 않는다::

    KMP_BLOCKTIME=200 ros2 run stack_traffic stack_traffic_node ...   # 옛 거동
"""
import os

os.environ.setdefault("KMP_BLOCKTIME", "0")
os.environ.setdefault("OMP_WAIT_POLICY", "PASSIVE")
